"""Live eval harness (FOUNDRY.md §5) — kernel-owned.

Runs ONE genome (the anima agent, rule-based) against a live ServUO shard,
routed through uo_proxy so the trajectory is captured INDEPENDENTLY of the agent
(anti-gaming: the agent can't influence what the kernel reads). After a bounded
window the agent is stopped, the trajectory parsed, and fitness + descriptor
computed by the canonical kernel.

    agent (python -m anima)  --->  uo_proxy (logs JSONL)  --->  ServUO :2594

The kernel drives anima and uo_proxy as SUBPROCESSES (`uv run python -m ...`); it
never imports them. fitness/descriptor parsing is pure stdlib in-process.

Eval protocol (FOUNDRY.md §5):
  - fixed start state: after the agent logs in, a kernel-owned GM session
    (gm.py) teleports it to its workplace, pins the profession skill baseline
    and hands it tools. The SCORED window starts after setup; parse_file's
    window_start guarantees the setup never contaminates fitness.
  - multi-seed: run_eval_multi() re-runs a genome on fresh accounts and
    averages (fitness mean, profession mode, mean-then-bin axes).
  - kernel-revert + worktree isolation are the orchestrator's job, not here.
"""

