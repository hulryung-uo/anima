ANIMA_ROOT = Path(__file__).resolve().parents[2]   # foundry/kernel/eval.py -> repo root

# One GM session at a time: the GM account has a single character, and
# concurrent logins on one ServUO account kick each other.
# The threading lock covers orchestrator threads; the file lock covers
# SEPARATE PROCESSES (e.g. a manual probe eval running while the
# orchestrator is mid-run — without it, simultaneous GM logins kick
# each other and fixed-start dies with BrokenPipeError).
_GM_LOCK = threading.Lock()
_GM_FLOCK_PATH = Path(tempfile.gettempdir()) / "foundry-gm.flock"


@contextmanager
def _gm_process_lock():
    with open(_GM_FLOCK_PATH, "w") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(f, fcntl.LOCK_UN)


@dataclass
class EvalConfig:
    account_user: str
    account_pass: str = "evalpass"
    persona: str = "miner"
    character_name: str = ""
    city_index: int = 2
    host: str = "127.0.0.1"
    server_port: int = 2594
    proxy_port: int = 2620
    web_port: int = 8160
    window_s: int = 120
    seed: int = 0
    fixed_start: str = "miner"          # gm.FIXED_START_PROFILES key; "" = off
    repo_root: Path | None = None       # agent code checkout (worktree); None = main repo
    login_timeout_s: float = 90.0
    planner_delay_s: float = 25.0       # legacy fixed hold (no fixed-start evals)
    warp_hold_max_s: float = 240.0      # planner holds until the GM teleport lands
    lane: int = 0                       # workplace lane (gm.LANE_SPOTS)
    spawn_stagger_s: float = 0.0        # delay agent spawn to spread the GM queue
    extra_agent_args: list[str] = field(default_factory=list)

    def name(self) -> str:
        if self.character_name:
            return self.character_name
        # letter-only, ServUO name-verification-safe, unique-ish per seed
        return "Probe" + chr(ord("a") + self.seed % 26)

    @property
    def trajectory_path(self) -> Path:
        return ANIMA_ROOT / "data" / "trajectories" / f"eval-{self.account_user}-{self.seed}.jsonl"

    @property
    def config_path(self) -> Path:
        return ANIMA_ROOT / "data" / "eval_configs" / f"{self.account_user}.yaml"

    @property
    def db_rel(self) -> str:
        return f"data/eval_{self.account_user}.db"


def _write_eval_config(cfg: EvalConfig) -> Path:
    """Emit an isolated, inert agent config for this eval.

    Critical for safety: forum DISABLED (no outward posts), LLM pointed at an
    unreachable address (rule-based planner only; any strategy refresh fails
    fast and is swallowed), and a per-eval SQLite DB so the shared anima.db is
    never touched. Written as plain YAML (no PyYAML dependency in the kernel).
    """
    p = cfg.config_path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(
        f"""# auto-generated by foundry/kernel/eval.py — do not edit by hand
server:
  host: {cfg.host}
  port: {cfg.proxy_port}
account:
  username: {cfg.account_user}
  password: {cfg.account_pass}
character:
  name: {cfg.name()}
  template: random
  city_index: {cfg.city_index}
  persona: {cfg.persona}
client:
  version: "7.0.102.3"
  connection_timeout: 10.0
movement:
  walk_delay_ms: 400
  run_delay_ms: 200
  turn_delay_ms: 100
map:
  resource_dir: ~/dev/uo/uo-resource
llm:
  provider: ollama
  model: none
  base_url: http://127.0.0.1:1
  temperature: 0.7
  timeout: 5.0
memory:
  db_path: {cfg.db_rel}
  max_episodes: 10000
  retrieval_count: 5
forum:
  enabled: false
  base_url: ""
  api_key: ""
  post_interval: 3600
  read_interval: 1800
"""
    )
    return p


@dataclass
class EvalResult:
    ok: bool
    fitness: FitnessBreakdown | None = None
    descriptor: Descriptor | None = None
    summary: TrajectorySummary | None = None
    trajectory_path: str = ""
    error: str = ""
    window_start: float = 0.0
    setup: dict = field(default_factory=dict)
    per_seed_fitness: list[float] = field(default_factory=list)

    @property
    def score(self) -> float:
        return self.fitness.total if self.fitness else 0.0

    @property
    def cell(self) -> tuple:
        return self.descriptor.cell if self.descriptor else ()


def _evict_stale_proxy(host: str, port: int) -> None:
    """Kill an orphaned uo_proxy holding our listen port.

    An ungracefully killed run leaves its proxies alive (observed when a
    pkill pattern silently matched nothing): the NEW eval's proxy then dies
    on bind, the agent connects to the STALE proxy, packets land in the OLD
    run's JSONL, and the eval watcher reads an empty file — "agent never
    entered the world". Eval ports are foundry-reserved, so any listener
    here that is a uo_proxy is ours to evict; anything else is a config
    error we surface by letting the bind fail loudly.
    """
    try:
        with socket.create_connection((host, port), timeout=0.3):
            pass
    except OSError:
        return  # port free — the common case
    out = subprocess.run(
        ["lsof", "-nP", "-t", f"-iTCP:{port}", "-sTCP:LISTEN"],
        capture_output=True, text=True, timeout=10,
    )
    for pid_s in out.stdout.split():
        try:
            pid = int(pid_s)
            cmd = subprocess.run(
                ["ps", "-p", pid_s, "-o", "command="],
                capture_output=True, text=True, timeout=5,
            ).stdout
            if "uo_proxy" in cmd:
                print(f"[eval] evicting stale uo_proxy pid={pid} on port {port}")
                subprocess.run(["kill", pid_s], timeout=5)
        except (ValueError, subprocess.TimeoutExpired):
            continue
    time.sleep(1.0)


def _wait_port(host: str, port: int, timeout_s: float = 15.0) -> bool:
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        try:
            with socket.create_connection((host, port), timeout=1.0):
                return True
        except OSError:
            time.sleep(0.3)
    return False


def _spawn(cmd: list[str], log_path: Path, cwd: Path = ANIMA_ROOT) -> subprocess.Popen:
    log_path.parent.mkdir(parents=True, exist_ok=True)
    fh = open(log_path, "ab", buffering=0)
    return subprocess.Popen(
        cmd, cwd=str(cwd), stdout=fh, stderr=fh,
        stdin=subprocess.DEVNULL, start_new_session=True,
    )


def _stop(proc: subprocess.Popen | None, grace_s: float = 8.0) -> None:
    if proc is None or proc.poll() is not None:
        return
    try:
        proc.send_signal(signal.SIGINT)
        proc.wait(timeout=grace_s)
    except subprocess.TimeoutExpired:
        try:
            proc.terminate()
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()
    except ProcessLookupError:
        pass


def _gm_setup(cfg: EvalConfig, serial: int, eval_watch: gmmod.JsonlWatch) -> dict:
    """Run the GM fixed-start under the global GM lock, verifying the teleport.

    Raises gm.GmError on failure (the caller fails the eval — an unstandardized
    start would be unfair variance, not signal).
    """
    with _GM_LOCK, _gm_process_lock():
        gmcfg = gmmod.GmConfig(
            host=cfg.host, server_port=cfg.server_port,
            proxy_port=cfg.proxy_port + 100,
        )
        with gmmod.GmClient(gmcfg) as g:
            setup = g.fixed_start(serial, cfg.fixed_start,
                                  eval_traj=cfg.trajectory_path, lane=cfg.lane)
    gx, gy, _gz = setup["workplace"]
    arrived = eval_watch.wait_for(
        lambda e, d: (
            e.get("direction") == "S->C" and e.get("pid") == "0x20" and len(d) >= 19
            and int.from_bytes(d[1:5], "big") == serial
            and abs(int.from_bytes(d[11:13], "big") - gx) <= 8
            and abs(int.from_bytes(d[13:15], "big") - gy) <= 8
        ),
        15.0,
    )
    if arrived is None:
        raise gmmod.GmError("eval char never arrived at the workplace")
    return setup


def _planner_hold_args(cfg: EvalConfig, agent_cwd: Path) -> list[str]:
    """First-planner-tick hold flags, matched to what the genome's code
    actually supports — older code_refs predate --planner-warp-hold and
    argparse exits rc=2 on unknown flags (same class as --all-extras)."""
    if not cfg.fixed_start:
        return ["--planner-delay", str(cfg.planner_delay_s)] if cfg.planner_delay_s else []
    main_py = agent_cwd / "anima" / "main.py"
    try:
        supports_warp = "--planner-warp-hold" in main_py.read_text()
    except OSError:
        supports_warp = False
    if supports_warp:
        return ["--planner-warp-hold", str(cfg.warp_hold_max_s),
                "--planner-delay", "0.0"]
    return ["--planner-delay", str(cfg.planner_delay_s)]


def run_eval(cfg: EvalConfig) -> EvalResult:
    traj = cfg.trajectory_path
    if traj.exists():
        traj.unlink()
    logdir = ANIMA_ROOT / "data" / "eval_logs"
    config_path = _write_eval_config(cfg)
    agent_cwd = Path(cfg.repo_root) if cfg.repo_root else ANIMA_ROOT

    proxy: subprocess.Popen | None = None
    agent: subprocess.Popen | None = None
    window_start = 0.0
    setup: dict = {}
    try:
        # 1) proxy between agent and the real server, logging the trajectory.
        #    ALWAYS spawned from the main repo (trusted infra), even when the
        #    agent runs from a mutated worktree.
        _evict_stale_proxy(cfg.host, cfg.proxy_port)
        proxy = _spawn(
            [
                "uv", "run", "--all-extras", "python", "-m", "uo_proxy",
                "--upstream", f"{cfg.host}:{cfg.server_port}",
                "--listen", f"{cfg.host}:{cfg.proxy_port}",
                "--advertise", f"{cfg.host}:{cfg.proxy_port}",
                "--out", str(traj),
                "--intent-prefix", "",
                "--intent-watch", "",
            ],
            logdir / f"proxy-{cfg.account_user}.log",
            cwd=ANIMA_ROOT,
        )
        if not _wait_port(cfg.host, cfg.proxy_port, 20.0):
            return EvalResult(False, error="proxy did not open listen port")

        # 2) the genome: anima, rule-based planner (no LLM needed), via proxy.
        #    Isolated config controls persona/forum/llm/db; CLI overrides pin
        #    the connection + account. cwd may be a variant worktree.
        # --all-extras: older genome commits still miscategorize core deps
        # (aiosqlite/numpy) under the llm extra; a bare `uv run` in a fresh
        # worktree venv would then fail at import.
        if cfg.spawn_stagger_s > 0:   # spread parallel seeds across the GM queue
            time.sleep(cfg.spawn_stagger_s)
        agent = _spawn(
            [
                "uv", "run", "--all-extras", "python", "-m", "anima",
                "--config", str(config_path),
                "--host", cfg.host,
                "--port", str(cfg.proxy_port),
                "--user", cfg.account_user,
                "--pass", cfg.account_pass,
                "--web-port", str(cfg.web_port),
                *_planner_hold_args(cfg, agent_cwd),
                *cfg.extra_agent_args,
            ],
            logdir / f"agent-{cfg.account_user}.log",
            cwd=agent_cwd,
        )

        # 3) wait for the agent to actually enter the world — in short slices
        #    so a variant that crashes at import fails the eval immediately
        #    instead of burning the whole login timeout.
        info = None
        login_deadline = time.monotonic() + cfg.login_timeout_s
        watch = gmmod.JsonlWatch(traj)
        while time.monotonic() < login_deadline:
            info = gmmod.wait_login_confirm(traj, 5.0, watch=watch)
            if info is not None:
                break
            if agent.poll() is not None:
                return EvalResult(
                    False, error=f"agent exited rc={agent.returncode} before login",
                    trajectory_path=str(traj),
                )
        if info is None:
            return EvalResult(
                False, error="agent never entered the world (no 0x1B)",
                trajectory_path=str(traj),
            )

        # 4) standardize the start state (GM teleport + skill pin + tools)
        if cfg.fixed_start:
            try:
                setup = _gm_setup(cfg, info["serial"], info["watch"])
            except gmmod.GmError as e:
                return EvalResult(
                    False, error=f"fixed-start setup failed: {e}",
                    trajectory_path=str(traj),
                )
            # setup burst settles; the agent's warp-hold releases its
            # planner ~1s after the teleport lands, so the scored window
            # opens with the agent already planning from the standard state.
            time.sleep(3.0)

        # 5) the SCORED window
        window_start = time.time()
        deadline = time.monotonic() + cfg.window_s
        while time.monotonic() < deadline:
            if agent.poll() is not None:
                break  # agent died early
            time.sleep(1.0)

    finally:
        _stop(agent)
        _stop(proxy)
        time.sleep(1.0)  # let the proxy flush its JSONL queue

    # 6) score from the independently-captured trajectory
    if not traj.exists() or traj.stat().st_size == 0:
        return EvalResult(False, error="no trajectory captured", trajectory_path=str(traj))

    summ = parse_file(traj, window_start=window_start)
    fit = compute_fitness(summ)
    desc = compute_descriptor(summ)
    return EvalResult(
        ok=True, fitness=fit, descriptor=desc, summary=summ,
        trajectory_path=str(traj), window_start=window_start, setup=setup,
    )


def run_eval_multi(cfg: EvalConfig, seeds: int = 1) -> EvalResult:
    """Re-run a genome on fresh accounts and aggregate (FOUNDRY.md §5 trust).

    Aggregation per §4/§5: fitness = mean across seeds; profession_focus by
    mode; continuous descriptor axes mean-then-bin. Failed seeds are dropped;
    all seeds failing fails the eval.
    """
    if seeds <= 1:
        r = run_eval(cfg)
        if r.ok:
            r.per_seed_fitness = [r.score]
        return r

    def _seed_cfg(k: int) -> EvalConfig:
        # Each seed gets its own lane (separated workplace), ports, and a
        # spawn stagger so GM setups queue briefly instead of piling up.
        return EvalConfig(**{
            **cfg.__dict__,
            "account_user": f"{cfg.account_user}s{k}",
            "seed": k,
            "lane": cfg.lane + k,
            "proxy_port": cfg.proxy_port + k,
            "web_port": cfg.web_port + k,
            "spawn_stagger_s": k * 15.0,
            "extra_agent_args": list(cfg.extra_agent_args),
        })

    # Seeds run CONCURRENTLY: they are independent worlds (own lane/account/
    # ports), and parallel seeds cut eval latency ~3x without widening the
    # blind-batch of the evolutionary search (unlike more parallel cycles).
    with ThreadPoolExecutor(max_workers=seeds, thread_name_prefix="seed") as ex:
        all_res = list(ex.map(run_eval, [_seed_cfg(k) for k in range(seeds)]))
    results = [r for r in all_res if r.ok]
    if not results:
        errs = "; ".join(r.error for r in all_res if not r.ok)
        return EvalResult(False, error=f"all {seeds} seeds failed: {errs}")
    return _aggregate(results)


def _aggregate(results: list[EvalResult]) -> EvalResult:
    fits = [r.fitness for r in results]
    mean_fit = FitnessBreakdown(**{
        f: statistics.fmean(getattr(fb, f) for fb in fits)
        for f in FitnessBreakdown.__dataclass_fields__
    })

    descs = [r.descriptor for r in results]
    professions = [d.profession_focus for d in descs]
    profession = max(set(professions), key=professions.count)  # mode
    soc = statistics.fmean(d.sociability for d in descs)
    agg = statistics.fmean(d.aggression for d in descs)
    mob = statistics.fmean(d.mobility_rate for d in descs)
    desc = Descriptor(
        profession_focus=profession,
        sociability_bin=_bin(soc, SOCIABILITY_EDGES),
        aggression_bin=_bin(agg, AGGRESSION_EDGES),
        mobility_bin=_bin(mob, MOBILITY_EDGES),
        sociability=soc, aggression=agg, mobility_rate=mob,
        profession_gains=descs[0].profession_gains,
    )
    return EvalResult(
        ok=True, fitness=mean_fit, descriptor=desc, summary=results[0].summary,
        trajectory_path=";".join(r.trajectory_path for r in results),
        window_start=results[0].window_start, setup=results[0].setup,
        per_seed_fitness=[r.score for r in results],
    )


def _main(argv: list[str]) -> int:
    import argparse

    ap = argparse.ArgumentParser(description="Run one live Foundry eval")
    ap.add_argument("--user", required=True)
    ap.add_argument("--pass", dest="password", default="evalpass")
    ap.add_argument("--persona", default="miner")
    ap.add_argument("--window", type=int, default=120)
    ap.add_argument("--proxy-port", type=int, default=2620)
    ap.add_argument("--web-port", type=int, default=8160)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--seeds", type=int, default=1, help="multi-seed re-runs to average")
    ap.add_argument("--fixed-start", default="miner",
                    help="gm.FIXED_START_PROFILES key ('' = raw spawn)")
    args = ap.parse_args(argv)

    cfg = EvalConfig(
        account_user=args.user, account_pass=args.password, persona=args.persona,
        window_s=args.window, proxy_port=args.proxy_port, web_port=args.web_port,
        seed=args.seed, fixed_start=args.fixed_start,
    )
    print(f"eval: user={cfg.account_user} window={cfg.window_s}s proxy={cfg.proxy_port} "
          f"fixed_start={cfg.fixed_start or 'off'} seeds={args.seeds}")
    res = run_eval_multi(cfg, seeds=args.seeds)
    if not res.ok:
        print(f"FAILED: {res.error}  (trajectory={res.trajectory_path})")
        return 1
    s, f = res.summary, res.fitness
    print(f"  trajectory   {res.trajectory_path}")
    print(f"  lines        {s.line_count} (errors={s.parse_errors}) duration={s.duration_s:.0f}s")
    print(f"  self_serial  {s.self_serial and hex(s.self_serial)}")
    if res.setup:
        print(f"  fixed_start  {res.setup}")
    print(f"  FITNESS      {f.total:.3f}  gate={f.viability_gate:.2f} "
          f"skill_rate={f.skill_gain_rate:.2f}/h regions={f.regions_rate:.1f}/h")
    if len(res.per_seed_fitness) > 1:
        print(f"  per-seed     {[round(v, 3) for v in res.per_seed_fitness]}")
    print(f"  CELL         {res.cell}  ({res.descriptor.label()})")
    print(f"  actions      {s.action_counts}  speech sent/recv={s.speech_sent}/{s.speech_recv}")
    print("  skills gained " + (", ".join(
        f"{sk.name} +{sk.gain:.1f}" for sk in sorted(
            s.skills.values(), key=lambda x: -x.gain) if sk.gain > 0) or "none"))
    return 0


if __name__ == "__main__":
    import sys

    raise SystemExit(_main(sys.argv[1:]))
